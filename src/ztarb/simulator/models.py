"""Synthetic domain models for the Zero-Trust discrete-event simulator."""

from __future__ import annotations
from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class SyntheticPrincipal:
    principal_id: str
    role: str
    home_devices: List[str]
    mean_volume: float = 0.02
    posture_mean: float = 0.85
    posture_std: float = 0.08
    rate_per_hour: float = 10.0


@dataclass
class SyntheticResource:
    resource_id: str
    sensitivity: float
    allow_restrict: bool
    require_mfa: bool


@dataclass
class EventOpportunity:
    """Action-independent request opportunity pre-generated by workload model."""
    opportunity_id: str
    timestamp: float
    principal: str
    role: str
    device: str
    resource: str
    operation: str
    desired_volume: float
    device_posture: float
    auth_failures: int
    unresolved_alerts: int
    
    # Ground truth (NEVER exposed to RL observation or controller!)
    is_attack: bool = False
    attack_family: Optional[str] = None
    target_volume: float = 0.0
    impact_delay_sec: float = 300.0  # Realized attack impact delay
